/** 首页推荐的 4 所院校（去重后取前 4） */
export function getFeaturedSchools(): School[] {
  const picks = [
    SCHOOLS[0],
    SCHOOLS[1],
    SCHOOLS.find((s) => s.tags.includes('双高计划') && s.city === '长沙') ?? SCHOOLS[4],
    SCHOOLS.find((s) => s.city === '衡阳') ?? SCHOOLS[8],
  ];
  const uniq: School[] = [];
  for (const p of picks) {
    if (p && !uniq.some((u) => u.id === p.id)) uniq.push(p);
  }
  return uniq.slice(0, 4);
}
